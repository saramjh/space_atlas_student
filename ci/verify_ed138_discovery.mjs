#!/usr/bin/env node
import assert from 'node:assert/strict';
import {readFileSync,statSync} from 'node:fs';
import {inferredDiameterKm, ed138SizeForPercent, ED138_HV} from '../assets/js/ed138-dwarf-planet.js';
const read=p=>readFileSync(p,'utf8');
const route='/solar-system/2026-ed138-dwarf-planet-candidate/';
const p='public'+route+'index.html';
const html=read(p),meta=JSON.parse(read('pages'+route+'meta.json'));
assert.equal(meta.path,route);
assert.equal(ED138_HV,3.19);
const near=(a,b,tol)=>assert.ok(Math.abs(a-b)<=tol,`${a} not within ${tol} of ${b}`);
near(inferredDiameterKm(.25),612,1);
near(inferredDiameterKm(.04),1530,1);
near(inferredDiameterKm(.10),968,1.5);
near(inferredDiameterKm(.25)*Math.sqrt(.25/.04),inferredDiameterKm(.04),.00001);
assert.ok(ed138SizeForPercent(4)>ed138SizeForPercent(10)&&ed138SizeForPercent(10)>ed138SizeForPercent(25));
for(const x of [0,-1,NaN,1.01,Infinity])assert.throws(()=>inferredDiameterKm(x),RangeError);
assert.match(html,/<h1>2026 ED138: could it be the sixth dwarf planet\?<\/h1>/);
assert.match(html,/Not yet\.<\/strong>/);
assert.match(html,/27 October 2026/);
assert.match(html,/612–1,530 km/);
assert.match(html,/43\.09 AU/);
assert.match(html,/46 AU/);
assert.match(html,/24\.4°/);
assert.match(html,/12:7 resonance/);
assert.match(html,/not a surface photograph|not a surface photograph\./i);
assert.match(html,/image unaltered apart from source-provider resolution selection/i);
assert.match(html,/id="ed138AlbedoLab"/);
assert.match(html,/id="ed138Albedo" type="range" min="4" max="25" value="10"/);
for(const x of ['4','10','25'])assert.match(html,new RegExp(`data-ed138-albedo="${x}"`));
assert.match(html,/class="ed138-qa"/);
assert.doesNotMatch(html,/"@type": "FAQPage"/);
assert.equal((html.match(/<h1\b/g)||[]).length,1);
assert.match(html,/"@type": "LearningResource"/);
assert.match(html,/"@type": "BreadcrumbList"/);
assert.match(html,/https:\/\/arxiv\.org\/abs\/2610\.38693/);
assert.match(html,/https:\/\/rubinobservatory\.org\/news\/rubin-first-dwarf-planet-candidate/);
assert.match(html,/https:\/\/iauarchive\.eso\.org\/public\/themes\/naming\//);
assert.match(html,/rel="canonical"/);
assert.match(html,/CC BY 4\.0/);
assert.match(html,/src="\/space_atlas_student\/assets\/images\/ed138-rubin-observation\.jpg"/);
const img=statSync('assets/images/ed138-rubin-observation.jpg');
assert.ok(img.size>20000&&img.size<650000,'source image should be real reasonably compressed Rubin observation');
const nav=read('templates/nav.html'),home=read('pages/index/content.html');
assert.match(nav,/2026-ed138-dwarf-planet-candidate/);assert.match(home,/2026-ed138-dwarf-planet-candidate/);
for(const page of ['pages/solar-system/pluto-dwarf-planet/content.html','pages/solar-system/astronomical-unit/content.html','pages/sources/space-resources-for-students/content.html'])assert.match(read(page),/2026-ed138-dwarf-planet-candidate/);
for(const back of ['solar-system/pluto-dwarf-planet','solar-system/astronomical-unit','sources/space-resources-for-students','solar-system/distance-scale'])assert.ok(html.includes('/space_atlas_student/'+back+'/'),'bidirectional learning link '+back);
const sitemap=read('public/sitemap.xml');
assert.match(sitemap,/2026-ed138-dwarf-planet-candidate/);
assert.equal((sitemap.match(/<url>/g)||[]).length,31);
const index=JSON.parse(read('public/assets/search-index.json'));
assert.ok(JSON.stringify(index).includes('2026 ED138'));
console.log('ED138_SCIENCE_ALBEDO_LICENSE_SOURCE_SEO_AEO_GEO_INTERNAL_LINKS_PASS');
